// 주문(OOC). relation-anatomy · daily-life-simulator 처럼 답변을 여러 번에 나눠 받는다.
// - 롤플 채팅 입력창 제한: 조각마다 1,500자 이하
// - 모델 출력 제한: 답 한 번에 항목 6개씩만 받아 잘리지 않게
// - 수치는 문자 한 개로 숨겨 채팅에서 결과가 드러나지 않게
import { ROW, TYPE_CODE } from './codebook.js';

export const INPUT_LIMIT = 1500;

const TABLE = [...ROW].map((c, lv) => `${lv}=${c}`).join(' ');
const TYPES = Object.entries(TYPE_CODE).map(([k, v]) => `${k}=${v}`).join(' ');

const SETUP = `[OOC 1/4 · 설정] 잠시 역할극 중단. 새로운 에피소드.
조건 : NPC/PC 기존설정, 관계성, 성격, 성향, 말투, 서사, 캐릭터정보, 유저노트, 로어북 종합참고
현재 NPC가 PC와의 관계에서 느끼는 무의식적 불안과 잠재 심리를 분석한다. 자각하는 감정과 자각하지 못하는 내면을 구분하여 수치화한다. NPC의 성격과 관계성에 맞춰 개별적으로 분석하며, 근거 없는 수치나 억지스러운 심리 해석은 금지한다.

[항목]
A01 건강 염려도: PC의 건강과 안전에 대한 걱정
A02 외도 불안도: PC가 다른 사람에게 마음을 빼앗길 두려움
A03 유기 불안도: PC에게 버려지거나 관계가 끝날 공포
A04 대체 불안도: 자신보다 좋은 사람이 나타날 것이라는 불안
A05 애정 비대칭 불안도: 자신만큼 사랑받지 못할지도 모른다는 걱정
A06 의존 불안도: PC에게 지나치게 의지하는 것에 대한 두려움
A07 친밀감 불안도: 가까워질수록 약점이나 본모습을 들키는 불안
A08 통제 상실 불안도: PC와 관계의 흐름을 통제하지 못하는 불안
A09 갈등 불안도: 다툼으로 관계가 손상될 것이라는 두려움
A10 미래 불안도: 현재의 관계가 지속될 수 있을지에 대한 걱정
A11 부담감 불안도: 자신이 PC에게 짐이 될지도 모른다는 염려
A12 상실 후유증 불안도: PC를 잃은 뒤 일상이 무너질 것이라는 공포
H01 무의식적 소유욕: PC를 자신의 영역으로 인식하는 정도
H02 감정적 취약성: PC 앞에서 드러나는 약점과 방어기제
H03 애착 유형: 안정형·불안형·회피형·혼란형 중 해당 양상과 그 강도
H04 확인 욕구: 사랑받고 있음을 확인하고 싶은 정도
H05 억압된 욕구: 원하지만 표현하지 못하는 욕망
H06 최악의 상상: PC와 관련해 가장 두려워하는 상황

[판정과 변환] 각 항목을 0~9 정수로 판정한다(근거 부족 시 4). 점수는 숫자로 쓰지 않고 아래 문자로만 쓴다.
${TABLE}

[답변 규칙] 이어서 보낼 메시지마다 정해진 항목만, 코드블록 하나에 한 항목 한 줄로 출력한다. 설명이나 서술은 블록 밖에 쓰지 않는다.
한 줄 형식: 코드 문자 | 상태값 | 설명
상태값은 현재 심리를 압축한 짧고 구체적인 문장(30자 안팎), 설명은 NPC의 내면에서 그 감정이 어떻게 작용하는지 2문장 이내(100자 안팎). 출력이 잘리지 않도록 길이를 지킨다. 숫자와 점수는 쓰지 않는다.

아직 시작하지 말고 "준비됨"이라고만 답해. 다음 메시지가 이어진다.`;

const part = (n, title, codes, extra = '') => `[OOC ${n}/4 · ${title}] 이어서 진행. 설정(1/4)의 기준으로 ${codes}를 판정해, 코드블록 하나에 아래 형식으로만 출력한다.
변환표: ${TABLE}
${extra}형식 예: A01 Q | 상태값 | 설명`;

const ANX1 = part(2, '불안 1', 'A01~A06');
const ANX2 = part(3, '불안 2', 'A07~A12').replace('형식 예: A01 Q', '형식 예: A07 Q');
const HIDDEN = `[OOC 4/4 · 숨겨진 심리] 이어서 진행. 설정(1/4)의 기준으로 H01~H06과 가장 깊은 불안을 판정해, 코드블록 하나에 아래 형식으로만 출력한다.
변환표: ${TABLE}
H03은 문자 뒤에 애착 유형 문자를 붙인다: ${TYPES} (예: H03 Q J | 상태값 | 설명)
마지막 줄: DEEP 속마음 한 문장 | 해설
DEEP은 NPC 본인조차 인정하기 싫어하는 가장 깊은 불안 한 가지다. 해설은 그 불안이 왜 가장 깊은지, 왜 인정하지 못하는지 3문장 이내로 쓴다.
형식 예: H01 Q | 상태값 | 설명`;

/** 채팅에 차례로 보낼 조각. expect: 그 조각의 답으로 받아야 할 항목 */
export const OOC_STEPS = [
  { title: '설정', text: SETUP, expect: [], reply: '준비됨' },
  { title: '불안 1~6', text: ANX1, expect: ['A01', 'A02', 'A03', 'A04', 'A05', 'A06'] },
  { title: '불안 7~12', text: ANX2, expect: ['A07', 'A08', 'A09', 'A10', 'A11', 'A12'] },
  { title: '숨겨진 심리', text: HIDDEN, expect: ['H01', 'H02', 'H03', 'H04', 'H05', 'H06', 'DEEP'] },
];
export const OOC_PARTS = OOC_STEPS.map((s) => s.text);
export const OOC_PROMPT = OOC_PARTS.join('\n\n');
